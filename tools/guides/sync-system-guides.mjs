import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourcePath = resolve(repo, 'data/system-guides.json');
const sourceText = await readFile(sourcePath, 'utf8');
const source = JSON.parse(sourceText);

const iosPath = resolve(
  repo,
  'mobile-apps/ios/TCGer/TCGer/Resources/Guides/system-guides.json',
);
const webPath = resolve(repo, 'frontend/public/guides/system-guides.json');
const webModulePath = resolve(repo, 'frontend/src/lib/guides/system-guides.generated.ts');
const convexPath = resolve(repo, 'convex-backend/convex/data/systemGuides.ts');
for (const path of [iosPath, webPath, webModulePath, convexPath]) {
  await mkdir(dirname(path), { recursive: true });
}

await writeFile(iosPath, `${JSON.stringify(source, null, 2)}\n`);
await writeFile(webPath, `${JSON.stringify(source, null, 2)}\n`);
await writeFile(
  webModulePath,
  `// Generated by tools/guides/sync-system-guides.mjs. Do not edit directly.\nexport const systemGuideDefinitions = ${JSON.stringify(source.guides, null, 2)} as const;\n`,
);
await writeFile(
  convexPath,
  `// Generated by tools/guides/sync-system-guides.mjs. Do not edit directly.\nexport const systemGuideDefinitions = ${JSON.stringify(source.guides, null, 2)} as const;\n`,
);
