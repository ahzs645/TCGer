import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourcePath = resolve(repo, 'data/system-guides.json');
const sourceText = await readFile(sourcePath, 'utf8');
const source = JSON.parse(sourceText);

async function withCatalogCounts(catalog) {
  try {
    const catalogDirectory = resolve(repo, 'data/catalog');
    const manifest = JSON.parse(await readFile(resolve(catalogDirectory, 'manifest.json'), 'utf8'));
    const packs = new Map();
    for (const [game, entry] of Object.entries(manifest.games ?? {})) {
      if (!entry?.file) continue;
      packs.set(game, JSON.parse(await readFile(resolve(catalogDirectory, entry.file), 'utf8')));
    }
    return {
      ...catalog,
      guides: catalog.guides
        .filter((guide) => packs.has(guide.tcg) || guide.ruleType === 'manual')
        .map((guide) => {
          const pack = packs.get(guide.tcg);
          if (!pack || !['tag', 'name'].includes(guide.ruleType)) return guide;
          const query = guide.ruleQuery?.toLowerCase();
          const cardCountHint = pack.cards.filter((card) => guide.ruleType === 'tag'
            ? (card.collectionTags ?? []).some((tag) => tag.toLowerCase() === query)
            : card.name.toLowerCase() === query).length;
          return { ...guide, cardCountHint };
        }),
    };
  } catch {
    return catalog;
  }
}

const generatedSource = await withCatalogCounts(source);

const iosPath = resolve(
  repo,
  'mobile-apps/ios/TCGer/TCGer/Resources/Guides/system-guides.json',
);
const webPath = resolve(repo, 'frontend/public/guides/system-guides.json');
const webModulePath = resolve(repo, 'frontend/src/lib/guides/system-guides.generated.ts');
const convexPath = resolve(repo, 'convex-backend/system-guides.generated.ts');
for (const path of [iosPath, webPath, webModulePath, convexPath]) {
  await mkdir(dirname(path), { recursive: true });
}

await writeFile(iosPath, `${JSON.stringify(generatedSource, null, 2)}\n`);
await writeFile(webPath, `${JSON.stringify(generatedSource, null, 2)}\n`);
await writeFile(
  webModulePath,
  `// Generated by tools/guides/sync-system-guides.mjs. Do not edit directly.\nexport const systemGuideDefinitions = ${JSON.stringify(generatedSource.guides, null, 2)} as const;\n`,
);
await writeFile(
  convexPath,
  `// Generated by tools/guides/sync-system-guides.mjs. Do not edit directly.\nexport const systemGuideDefinitions = ${JSON.stringify(generatedSource.guides, null, 2)} as const;\n`,
);
